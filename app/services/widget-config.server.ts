// Merchant-editable storefront chat widget copy/colors/layout/behavior —
// greeting, bubble/panel/text/border colors, panel size/position/corner
// radius, disclaimer text+toggle, starter-chip labels/messages, and whether
// the bubble auto-hides while the panel is open — set on the app's
// Messenger admin page (app/routes/app.messenger-orders.tsx) instead of the
// Theme Editor. Read by apps.schedule-rules.widget-config.ts on every
// storefront page load (the widget script fetches it before mounting), so
// this is cached in-process the same way cod-facts.server.ts caches its
// Shopify lookup — except this is a plain Postgres read (no Shopify Admin
// API call), so no lazy-import trick is needed.
//
// Null column (or a missing row entirely) = use the built-in default below —
// same convention as ReminderConfig's email templates. This means an
// unconfigured shop, a missing row, or a DB hiccup all degrade to exactly
// what the widget already hardcoded/read from the Theme Editor before this
// existed — never a blank or broken widget.
//
// Deliberately independent of the storefront theme's own colors — see
// docs/widget-design-system.md for why (a theme redesign should never
// silently change the widget's look).

import prisma from "../db.server";

export type WidgetChip = { label: string; message: string };

export type WidgetConfigFacts = {
  greeting: string;
  bubbleColor: string;
  supportPhone: string;
  trackLabel: string;
  chips: WidgetChip[];
  panelBg: string;
  textColor: string;
  mutedColor: string;
  borderColor: string;
  panelSize: "compact" | "standard" | "large";
  cornerRadius: number;
  position: "left" | "right";
  disclaimerText: string;
  showDisclaimer: boolean;
  autoHideBubble: boolean;
};

const PANEL_SIZES = new Set(["compact", "standard", "large"]);
const POSITIONS = new Set(["left", "right"]);
const CORNER_RADIUS_MIN = 4;
const CORNER_RADIUS_MAX = 28;

// Mirrors the live defaults introduced this session (storefront-chat-widget.js
// / app-embed.liquid) — an empty WidgetConfig row changes nothing.
export const WIDGET_CONFIG_DEFAULTS: WidgetConfigFacts = {
  greeting: "Hi! Ask us about bouquets, delivery dates, or your order status. 🌸",
  bubbleColor: "#9a6a60",
  supportPhone: "0962 422 4085",
  trackLabel: "🔎 Track my order",
  chips: [
    { label: "🚚 Delivery coverage & fees", message: "Where do you deliver, and how much is the delivery fee?" },
    { label: "💳 Payment options", message: "What payment methods do you accept?" },
    { label: "🌸 Cancel/reschedule order", message: "How do I cancel or reschedule my order?" },
  ],
  panelBg: "#ffffff",
  textColor: "#3b3230",
  mutedColor: "#6d6560",
  borderColor: "#e9ded9",
  panelSize: "standard",
  cornerRadius: 16,
  position: "right",
  disclaimerText: "Answers are generated by AI and may not always be accurate.",
  showDisclaimer: true,
  autoHideBubble: false,
};

const CACHE_TTL_MS = 5 * 60 * 1000;

let cached: { shop: string; facts: WidgetConfigFacts; expiresAt: number } | null = null;

/** Test seam — drops the memo so a suite can exercise a fresh fetch. */
export function resetWidgetConfigCache(): void {
  cached = null;
}

function pick(value: string | null | undefined, fallback: string): string {
  const trimmed = value?.trim();
  return trimmed ? trimmed : fallback;
}

function pickEnum<T extends string>(value: string | null | undefined, allowed: Set<string>, fallback: T): T {
  return value && allowed.has(value) ? (value as T) : fallback;
}

function pickInt(value: number | null | undefined, fallback: number, min: number, max: number): number {
  if (value === null || value === undefined || !Number.isFinite(value)) return fallback;
  return Math.min(max, Math.max(min, Math.round(value)));
}

function pickBool(value: boolean | null | undefined, fallback: boolean): boolean {
  return value === null || value === undefined ? fallback : value;
}

export async function loadWidgetConfig(shop: string, now: number = Date.now()): Promise<WidgetConfigFacts> {
  if (cached && cached.shop === shop && cached.expiresAt > now) {
    return cached.facts;
  }

  try {
    const row = await prisma.widgetConfig.findUnique({ where: { shop } });
    const defaults = WIDGET_CONFIG_DEFAULTS;
    const facts: WidgetConfigFacts = {
      greeting: pick(row?.greeting, defaults.greeting),
      bubbleColor: pick(row?.bubbleColor, defaults.bubbleColor),
      supportPhone: pick(row?.supportPhone, defaults.supportPhone),
      trackLabel: pick(row?.trackLabel, defaults.trackLabel),
      chips: [
        { label: pick(row?.chip2Label, defaults.chips[0].label), message: pick(row?.chip2Message, defaults.chips[0].message) },
        { label: pick(row?.chip3Label, defaults.chips[1].label), message: pick(row?.chip3Message, defaults.chips[1].message) },
        { label: pick(row?.chip4Label, defaults.chips[2].label), message: pick(row?.chip4Message, defaults.chips[2].message) },
      ],
      panelBg: pick(row?.panelBg, defaults.panelBg),
      textColor: pick(row?.textColor, defaults.textColor),
      mutedColor: pick(row?.mutedColor, defaults.mutedColor),
      borderColor: pick(row?.borderColor, defaults.borderColor),
      panelSize: pickEnum(row?.panelSize, PANEL_SIZES, defaults.panelSize),
      cornerRadius: pickInt(row?.cornerRadius, defaults.cornerRadius, CORNER_RADIUS_MIN, CORNER_RADIUS_MAX),
      position: pickEnum(row?.position, POSITIONS, defaults.position),
      disclaimerText: pick(row?.disclaimerText, defaults.disclaimerText),
      showDisclaimer: pickBool(row?.showDisclaimer, defaults.showDisclaimer),
      autoHideBubble: pickBool(row?.autoHideBubble, defaults.autoHideBubble),
    };
    cached = { shop, facts, expiresAt: now + CACHE_TTL_MS };
    return facts;
  } catch (error) {
    console.warn(
      `[widget-config] falling back to defaults: ${
        error instanceof Error ? error.message : String(error)
      }`,
    );
    return WIDGET_CONFIG_DEFAULTS;
  }
}
